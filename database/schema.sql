CREATE TABLE IF NOT EXISTS __PREFIX__ib_sections (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(180) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS __PREFIX__ib_news (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(200) NOT NULL, body MEDIUMTEXT NOT NULL, picture VARCHAR(64) DEFAULT NULL,
 published TINYINT NOT NULL DEFAULT 0, is_new TINYINT NOT NULL DEFAULT 0,
 views BIGINT UNSIGNED NOT NULL DEFAULT 0, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX (published, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS __PREFIX__ib_docs (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 section_id INT UNSIGNED NULL, title VARCHAR(200) NOT NULL,
 file_key VARCHAR(64) NOT NULL, file_name VARCHAR(255) NOT NULL,
 mime VARCHAR(100) NOT NULL, file_size BIGINT UNSIGNED NOT NULL,
 published TINYINT NOT NULL DEFAULT 0, position INT NOT NULL DEFAULT 0,
 for_crypto TINYINT NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (section_id) REFERENCES __PREFIX__ib_sections(id) ON DELETE SET NULL,
 INDEX (published, position)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS __PREFIX__ib_tests (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(200) NOT NULL, description TEXT NOT NULL,
 questions MEDIUMTEXT NOT NULL, revision CHAR(32) NOT NULL,
 published TINYINT NOT NULL DEFAULT 0, position INT NOT NULL DEFAULT 0,
 INDEX (published, position)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS __PREFIX__ib_results (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 attempt CHAR(32) NOT NULL UNIQUE, participant VARCHAR(120) NOT NULL,
 test_id INT UNSIGNED NOT NULL, test_title VARCHAR(200) NOT NULL,
 score INT UNSIGNED NOT NULL, total INT UNSIGNED NOT NULL,
 details MEDIUMTEXT NOT NULL, ip VARCHAR(45) NOT NULL,
 login VARCHAR(180) NOT NULL, network_login VARCHAR(180) NOT NULL,
 user_agent VARCHAR(255) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;


CREATE TABLE IF NOT EXISTS __PREFIX__ib_settings (
 setting_key VARCHAR(48) NOT NULL PRIMARY KEY,
 setting_value MEDIUMTEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS __PREFIX__ib_page_views (
 page_key VARCHAR(48) NOT NULL PRIMARY KEY,
 views BIGINT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
